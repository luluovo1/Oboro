#!/usr/bin/env bash
#===- obfuscation-tests.sh - run only the Obfuscation lit suite ----------===//
#
# Adapted from upstream .ci/monolithic-linux.sh, but scoped to a single test
# directory: it builds `opt` plus the lit helper tools and runs
# llvm/test/Transforms/Obfuscation only.
#
# This script is never invoked automatically.  The GitHub workflow that calls
# it is workflow_dispatch-only.
#
# Environment:
#   TEST_PATH   lit directory to run (default: llvm/test/Transforms/Obfuscation)
#   BUILD_DIR   build directory (default: <repo>/build-obfuscation)
#   BUILD_TYPE  CMAKE_BUILD_TYPE (default: Release)
#   JOBS        parallel build jobs (default: number of CPUs)
#
#===----------------------------------------------------------------------===//

set -euo pipefail

MONOREPO_ROOT="${MONOREPO_ROOT:-$(git rev-parse --show-toplevel)}"
BUILD_DIR="${BUILD_DIR:-${MONOREPO_ROOT}/build-obfuscation}"
TEST_PATH="${TEST_PATH:-llvm/test/Transforms/Obfuscation}"
BUILD_TYPE="${BUILD_TYPE:-Release}"
JOBS="${JOBS:-$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)}"

TEST_DIR="${MONOREPO_ROOT}/${TEST_PATH}"
if ! compgen -G "${TEST_DIR}/*.ll" > /dev/null; then
  echo "error: no .ll tests under ${TEST_PATH}" >&2
  exit 1
fi

CCACHE_ARGS=()
if command -v ccache > /dev/null 2>&1; then
  CCACHE_ARGS=(-DLLVM_CCACHE_BUILD=ON)
fi

echo "--- cmake (${BUILD_TYPE})"
cmake -S "${MONOREPO_ROOT}/llvm" -B "${BUILD_DIR}" -G Ninja \
  -DCMAKE_BUILD_TYPE="${BUILD_TYPE}" \
  -DLLVM_ENABLE_ASSERTIONS=ON \
  -DLLVM_ENABLE_PROJECTS="" \
  -DLLVM_TARGETS_TO_BUILD="X86;AArch64;ARM" \
  -DLLVM_INCLUDE_TESTS=ON \
  -DLLVM_BUILD_TESTS=ON \
  ${CCACHE_ARGS[@]+"${CCACHE_ARGS[@]}"}

echo "--- ninja (opt + lit helpers)"
# llvm-lit itself is generated by CMake configure_file, not a ninja target.
# llvm-config is required at lit startup: lit/llvm/config.py shells out to
# `llvm-config --assertion-mode --build-mode` and aborts if it is missing.
ninja -C "${BUILD_DIR}" -j "${JOBS}" opt llvm-config FileCheck count not

echo "--- lit: ${TEST_PATH}"
"${BUILD_DIR}/bin/llvm-lit" -v \
  --xunit-xml-output "${BUILD_DIR}/obfuscation-results.xml" \
  --timeout=1200 \
  --time-tests \
  "${TEST_DIR}"
